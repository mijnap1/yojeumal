const start = new Date("2020-01-01T00:00:00");
const end = new Date("2026-11-04T00:00:00");
const day = 86_400_000;
const pixelsPerDay = 3.15;
const trackWidth = Math.round((end - start) / day * pixelsPerDay);
// 밀집 구간에서도 아직 사용 중인 줄을 강제로 재사용하지 않도록 여유 줄을 둔다.
const laneLastRight = Array(14).fill(-Infinity);
const minimumLabelGap = 28;
const eventsBySlug = new Map();

track.style.setProperty("--track-width", `${trackWidth}px`);

function xFor(date) {
  // 월만 확인된 항목은 배치용으로 월 중앙에 놓는다. 최초 유행일을 뜻하지 않는다.
  const positionDate = date.length === 7 ? `${date}-15` : date;
  return ((new Date(`${positionDate}T00:00:00`) - start) / day) * pixelsPerDay;
}

function displayMonth(date) {
  return date.slice(0, 7).replace("-", ".");
}

function estimatedLabelWidth(term) {
  const textWidth = Array.from(term).reduce((width, character) => {
    return width + (/[ㄱ-힝]/.test(character) ? 22 : 12);
  }, 0);
  return Math.max(88, textWidth);
}

function termToSlug(term) {
  return term
    .normalize("NFC")
    .toLocaleLowerCase("ko-KR")
    .replace(/[^\p{Letter}\p{Number}]+/gu, "-")
    .replace(/^-+|-+$/g, "");
}

function readHashSlug() {
  try {
    return decodeURIComponent(window.location.hash.slice(1));
  } catch {
    return window.location.hash.slice(1);
  }
}

function replaceHash(term = "") {
  const base = `${window.location.pathname}${window.location.search}`;
  const hash = term ? `#${encodeURIComponent(termToSlug(term))}` : "";
  window.history.replaceState(null, "", `${base}${hash}`);
}

