const dragHintStorageKey = "yojeumal-drag-hint-seen";
let dragHintShowTimer = null;
let dragHintHideTimer = null;

function hasSeenDragHint() {
  try {
    return window.sessionStorage.getItem(dragHintStorageKey) === "true";
  } catch {
    return false;
  }
}

function rememberDragHint() {
  try {
    window.sessionStorage.setItem(dragHintStorageKey, "true");
  } catch {
    // Storage can be unavailable in privacy-restricted browsers.
  }
}

function dismissDragHint(remember = true) {
  window.clearTimeout(dragHintShowTimer);
  window.clearTimeout(dragHintHideTimer);
  dragHint.classList.remove("visible");
  if (remember) rememberDragHint();
}

function showDragHint() {
  if (hasSeenDragHint() || window.location.hash) return;
  dragHintShowTimer = window.setTimeout(() => dragHint.classList.add("visible"), 450);
  dragHintHideTimer = window.setTimeout(dismissDragHint, 4800);
}

function openEventFromHash() {
  const slug = readHashSlug();
  if (!slug) return false;

  const entry = eventsBySlug.get(slug);
  if (!entry) return false;

  timeline.style.scrollBehavior = "auto";
  timeline.scrollLeft = entry.x;
  if (selectedEvent !== entry.event) {
    selectEvent(entry.event, entry.date, entry.term, false);
  }
  dismissDragHint(false);
  return true;
}

function jumpToYear(x) {
  const reducedMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  stopTimelineMomentum();
  dismissDragHint();
  timeline.scrollTo({
    left: x + timeline.clientWidth * 0.25,
    behavior: reducedMotion ? "auto" : "smooth",
  });
}

function updateCurrentYear() {
  const current = yearStops.findLast(({ x }) => timeline.scrollLeft >= x) ?? yearStops[0];
  yearStops.forEach(({ button }) => {
    if (button === current.button) button.setAttribute("aria-current", "true");
    else button.removeAttribute("aria-current");
  });
}

function centerPresent() {
  timeline.style.scrollBehavior = "auto";
  timeline.scrollLeft = timeline.scrollWidth;
}

window.addEventListener("load", () => requestAnimationFrame(() => {
  if (!openEventFromHash()) centerPresent();
  updateCurrentYear();
  showDragHint();
}));
